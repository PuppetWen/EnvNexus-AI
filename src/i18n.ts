const dictionaries: Record<AppLanguage, Dictionary> = {
  "zh-CN": {},
  "zh-TW": traditionalChinese,
  "en-US": english,
  "ja-JP": japanese,
  "ko-KR": korean,
};

export function localizeUi(root: HTMLElement, language: AppLanguage): void {
  document.documentElement.lang = language;
  const dictionary = dictionaries[language];
  if (!Object.keys(dictionary).length) return;

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    const raw = node.nodeValue ?? "";
    const value = raw.trim();
    const translated = dictionary[value];
    if (translated) {
      node.nodeValue = raw.replace(value, translated);
    }
    node = walker.nextNode();
  }

  root.querySelectorAll<HTMLInputElement>("[placeholder]").forEach((input) => {
    const translated = dictionary[input.placeholder];
    if (translated) input.placeholder = translated;
  });
}
